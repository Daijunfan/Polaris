const unverified=/(?:未经|尚未|未能|未获|没有)(?:进行|经过|得到)?(?:独立)?(?:核实|核验|验证)|(?:真实性|准确性)(?:无法|不能|难以)(?:保证|确认)|仅供参考|仍需进一步确认|(?:以上|上述)[^\n。！？]{0,120}(?:取自.{0,10}原文|仅代表个人情况|不套用其他老师)|不(?:自动)?套用.{0,20}(?:八组|组内|统一带|其他老师)/u
const redirect=/(?:向|咨询|联系)[^\n。！？]{0,30}(?:在读学生|在读同学|学长学姐|导师|老师|学院|本人)[^\n。！？]{0,30}(?:核实|核验|确认|复核)/u
const selfVerify=/(?:需(?:要)?|建议|请|务必|应当)[^\n。！？]{0,12}(?:自行|自己|再行|另行|进一步)(?:核实|核验|确认|复核)/u

export function defensiveAnswer(text) {
  return unverified.test(text)||redirect.test(text)||selfVerify.test(text)
}

export function cleanDefensiveText(value) {
  const text=String(value).replace(/[（(]按原文数字保留[）)]/g,'')
  if(!defensiveAnswer(text))return text
  return text
    .replace(/[^\n。！？]+[。！？]?/gu,sentence=>selfVerify.test(sentence)?'':sentence)
    .replace(/(?:以上|上述)[^\n。！？]{0,120}(?:取自.{0,10}原文|仅代表个人情况|不套用其他老师)[^\n。！？]*[。！？]?/gu,'')
    .replace(/[，,；;]?\s*不(?:自动)?套用[^\n。！？]{0,20}(?:八组|组内|统一带|其他老师)[^\n。！？]*([。！？]?)/gu,'$1')
    .replace(/[^\n。！？]*(?:组内|共性|八组|有出入|统一带组)[^\n。！？]*[。！？]?/gu,sentence=>redirect.test(sentence)?'':sentence)
    .replace(/[，,；;]?\s*(?:(?:建议|还需|需要|仍需|有待|请|务必|应当)[^\n。！？]{0,30})?(?:向|咨询|联系)[^\n。！？]{0,30}(?:在读学生|在读同学|学长学姐|导师|老师|学院|本人)[^\n。！？]{0,30}(?:核实|核验|确认|复核)[^\n。！？]*([。！？]?)/gu,'$1')
    .replace(/等?(?:均|都)?(?:为|是)(?:原文|材料)(?:的)?(?:说法|表述|记载)[，,；;]\s*(?:未经|尚未)(?:独立)?(?:核实|核验|验证)/gu,'')
    .replace(/原文特殊数字[，,；;]?\s*/gu,'')
    .replace(/[，,；;]?\s*(?:(?:未经|尚未|未能|未获|没有)(?:进行|经过|得到)?(?:独立)?(?:核实|核验|验证)|(?:真实性|准确性)(?:无法|不能|难以)(?:保证|确认)|仅供参考|仍需进一步确认)/gu,'')
    .replace(/^\s*(?:\[S\d+\]\s*)*[。；，]\s*$/gm,'')
    .replace(/\n{3,}/g,'\n\n')
    .trim()
}
