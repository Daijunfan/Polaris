  if(!asksCertainty)result=result
    .replace(/[，,；;]?\s*样本(?:量|数)(?:很|极|过|太)(?:小|少)[^，,；;。！？\n]*/gu,'')
    .replace(/(?:这些|以上|上述)?(?:仅为|只是|仅是)历史样本[，,；;]?\s*(?:并非|不是|不等于|不代表)(?:录取门槛|录取分数线|录取保证)[^，,；;。！？\n]*/gu,'')
