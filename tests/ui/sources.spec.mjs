import {test,expect} from '@playwright/test'

test('网页来源按老师查找，显示原始网页和抓取日期，关闭后保留聊天',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'资料与来源'}).click()
  const dialog=page.getByRole('dialog',{name:'资料与来源'})
  await dialog.getByRole('textbox',{name:'查找资料来源'}).fill('付俊松')
  const rows=dialog.locator('.source-row')
  await expect(rows).toHaveCount(4)
  await expect(dialog).toContainText('学校官网')
  await expect(dialog).toContainText('第三方资料')
  await expect(dialog).toContainText('第三方评价')
  await expect(dialog).not.toContainText('维护者补充')
  await expect(dialog).toContainText('抓取')
  const links=dialog.getByRole('link',{name:'查看原始网页'})
  await expect(links).toHaveCount(3)
  expect(await links.first().getAttribute('href')).toMatch(/^https:\/\//)
  expect(await links.first().getAttribute('rel')).toBe('noopener noreferrer')
  expect(await dialog.innerText()).not.toMatch(/profile_id|mentor_id|source_locator|\/Users\//)
  await dialog.getByRole('textbox',{name:'查找资料来源'}).fill('不存在的资料来源')
  await expect(dialog).toContainText('没有匹配的来源')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('textbox',{name:'向北极星提问'})).toBeVisible()
})
