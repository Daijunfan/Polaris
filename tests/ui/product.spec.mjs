test('长表格不串列，数字与缺失值跟随整列对齐，原文可以展开与排序', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message))
  await comparison(page)
  const artifact = page.getByTestId('artifact').first(), table = artifact.locator('table')
  const tableView=artifact.getByRole('button',{name:'表格',exact:true})
  if(await tableView.count())await tableView.click()
  await expect(table.locator('tbody tr')).toHaveCount(5)
  const alignments = await table.evaluate(element => {
    const label = element.querySelector('thead th:nth-child(3) button span')
    const expected = label.getBoundingClientRect().right
    return [...element.querySelectorAll('tbody tr td:nth-child(3)')].map(cell => {
      const range = document.createRange(); range.selectNodeContents(cell)
      return { className: cell.className, offset: Math.abs(range.getBoundingClientRect().right - expected) }
    })
  })
  expect(alignments.every(a => a.className.includes('numeric') && a.offset < 1.5)).toBe(true)
  expect(await table.locator('td').evaluateAll(cells => cells.every(cell => cell.scrollWidth <= cell.clientWidth + 1))).toBe(true)
  const row = table.locator('tbody tr').filter({ hasText: '李丽香' })
  await row.getByText('展开全文', { exact: true }).first().click()
  await expect(row.locator('details[open] .cell-full').first()).toBeVisible()
  await table.getByRole('button', { name: /按培养体验评分/ }).click()
  await expect(table.locator('tbody tr').last().locator('td').nth(2)).toHaveClass(/missing/)
  await expect(row.locator('details[open] .cell-full').first()).toBeVisible()
  const markdownTable = page.locator('.markdown table')
  await expect(markdownTable.locator('tbody tr').nth(1).locator('td').nth(2)).toHaveClass(/numeric.*missing/)
  await expect(markdownTable).not.toContainText('NaN')
  await page.getByRole('button', { name: /展开表格 导师培养条件/ }).click()
  const dialog = page.getByRole('dialog', { name: '导师培养条件：长文本与缺失值对比' })
  await expect(dialog).toBeVisible()
  expect(await dialog.locator('.data-table-scroll').evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true)
  await page.screenshot({ path: '.local/qa/comparison-expanded.png', fullPage: true })
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  expect(errors).toEqual([])
})

