test('招生类型以考研和保研呈现，全部只有考研的导师与导出结果一致', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('北极星')
  await expect(page.getByRole('button', { name: '北极星首页' })).toBeVisible()
  await page.getByRole('textbox', { name: '向北极星提问' }).fill('招生类型验收：列出全部只有考研学生的导师和考研保研人数')
  await page.getByRole('button', { name: '发送问题' }).click()
  await expect(page.getByRole('button', { name: '复制回答' })).toBeVisible()
  const mentors = page.getByTestId('artifact').filter({ hasText: '全部只有考研学生的导师' })
  await expect(mentors.locator('tbody tr')).toHaveCount(7)
  for (const name of ['昌硕', '崔志伟', '康梓峰', '雷敏', '刘浩（李小勇）', '刘科伟', '马金鑫']) await expect(mentors.locator('tbody')).toContainText(name)
  const types = page.getByTestId('artifact').filter({ hasText: '名册招生类型人数' })
  await expect(types.locator('tbody tr').filter({ hasText: '保研' })).toContainText('258')
  await expect(types.locator('tbody tr').filter({ hasText: '考研' })).toContainText('118')
  await expect(types).not.toContainText('recommended')
  const pending = page.waitForEvent('download')
  await types.getByRole('button', { name: '下载 名册招生类型人数 CSV' }).click()
  const download = await pending, csv = await fs.readFile(await download.path(), 'utf8')
  expect(csv).toContain('保研'); expect(csv).toContain('258'); expect(csv).not.toContain('recommended')
  const chart = page.getByTestId('artifact').filter({ hasText: '名册招生类型分布' })
  await expect(chart.locator('.chart-category')).toContainText(['保研', '考研'])
  await expect(chart).not.toContainText('recommended')
  const svgPending = page.waitForEvent('download')
  await chart.getByRole('button', { name: '导出 SVG' }).click()
  const svgDownload = await svgPending, svg = await fs.readFile(await svgDownload.path(), 'utf8')
  expect(svg).toContain('保研'); expect(svg).toContain('北极星'); expect(svg).not.toContain('recommended')
})

