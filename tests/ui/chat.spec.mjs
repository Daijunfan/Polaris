test('五种可视化能渲染数据并导出，散点提示能识别导师', async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('textbox', { name: '向北极星提问' }).fill('模拟多图')
  await page.getByRole('button', { name: '发送问题' }).click()
  await expect(page.getByRole('button', { name: '复制回答' })).toBeVisible()
  await expect(page.getByTestId('artifact')).toHaveCount(5)
  await expect(page.locator('.artifact svg[role="img"]')).toHaveCount(3)
  await expect(page.locator('.artifact .metric-item')).toHaveCount(4)
  await expect(page.locator('.artifact table tbody tr')).toHaveCount(4)
  const scatter = page.locator('.artifact').filter({ has: page.getByRole('heading', { name: '渲染验证 scatter' }) })
  await scatter.locator('circle').first().focus()
  await expect(scatter.locator('.chart-tooltip b')).not.toHaveText('5')
  expect(await page.locator('.artifact svg').evaluateAll(nodes => nodes.every(node => !/NaN|Infinity/.test(node.innerHTML)))).toBe(true)
  const bar = page.locator('.artifact').filter({ has: page.getByRole('heading', { name: '渲染验证 bar' }) })
  const csv = page.waitForEvent('download')
  await bar.getByRole('button', { name: /CSV/ }).click()
  expect((await csv).suggestedFilename()).toContain('.csv')
  const svg = page.waitForEvent('download')
  await bar.getByRole('button', { name: '导出 SVG' }).click()
  const downloaded = await svg
  expect(downloaded.suggestedFilename()).toContain('.svg')
  const contents = await fs.readFile(await downloaded.path(), 'utf8')
  expect(contents).toContain('渲染验证 bar')
  expect(contents).toContain('培养体验评分 / 5')
  expect(contents).toContain('来源：第三方评价')
  expect(errors).toEqual([])
})

test('模型可以从列表选择、在设置中切换，并在刷新后保留', async ({ page }) => {
  await page.goto('/')
  const picker = page.getByRole('combobox', { name: '选择模型' })
  await picker.focus()
  await expect(picker.locator('option[value="test-alt"]')).toHaveCount(1)
  await picker.selectOption('test-alt')
  await expect(picker).toHaveValue('test-alt')
  await page.reload()
  await expect(picker).toHaveValue('test-alt')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await page.getByRole('button', { name: '获取模型列表' }).click()
  await page.getByRole('combobox', { name: '模型', exact: true }).selectOption('test-agent')
  await page.getByRole('button', { name: '连接并保存' }).click()
  await expect(picker).toHaveValue('test-agent')
})
