import {test,expect} from '@playwright/test'

test('侧栏拖拽、限宽、键盘与双击复位，刷新保留',async({page})=>{
  await page.goto('/')
  const pane=page.locator('.sidebar-pane'),grip=page.getByRole('separator',{name:'调整侧栏宽度'})
  const width=()=>pane.evaluate(e=>e.getBoundingClientRect().width)
  await expect(grip).toBeVisible()
  const b=await grip.boundingBox()
  await page.mouse.move(b.x+5,b.y+200);await page.mouse.down();await page.mouse.move(b.x+165,b.y+200,{steps:12});await page.mouse.up()
  await expect.poll(width).toBe(420)
  await page.reload();await expect.poll(width).toBe(420)
  await grip.focus();await page.keyboard.press('End');await expect.poll(width).toBe(480)
  await page.keyboard.press('Home');await expect.poll(width).toBe(200)
  await grip.dblclick();await grip.focus()
  await page.keyboard.press('ArrowRight');await expect.poll(width).toBe(276)
  await expect(grip).toHaveAttribute('aria-valuenow','276')
  await page.setViewportSize({width:800,height:900})
  await expect(grip).toHaveAttribute('aria-valuemax','320')
  await page.keyboard.press('End');await expect.poll(width).toBe(320)
  await expect(page.locator('html')).not.toHaveClass(/resizing-sidebar/)
})

test('收起后释放宽度、展开入口可见；手机抽屉不受桌面偏好影响',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'收起侧栏',exact:true}).click()
  await expect.poll(()=>page.locator('.sidebar-pane').evaluate(e=>e.getBoundingClientRect().width)).toBe(0)
  await page.reload();await expect(page.getByRole('button',{name:'展开侧栏',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'展开侧栏',exact:true}).click()
  await expect(page.getByRole('button',{name:'开启新对话',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'收起侧栏',exact:true}).click()
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'打开对话列表',exact:true}).click()
  await expect(page.getByRole('button',{name:'开启新对话',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'关闭对话列表',exact:true}).click()
  await expect(page.getByRole('button',{name:'开启新对话',exact:true})).not.toBeVisible()
  expect(await page.locator('body').evaluate(e=>e.scrollWidth)).toBe(390)
})

test('回答完成时不夺走侧栏键盘调整的焦点',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('模拟持续输出：保留用户当前操作焦点')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.locator('.work-step.running').last()).toContainText('正在输出回答')
  const grip=page.getByRole('separator',{name:'调整侧栏宽度'})
  await grip.focus();await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible({timeout:10000})
  await expect(grip).toBeFocused()
})
