import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('普通对话直接完成跨学院前30名，有名次列与完整数据，不出现目标入口',async({page})=>{
  await page.goto('/')
  await expect(page.locator('.goal-command,.goal-state')).toHaveCount(0)
  expect(await page.locator('.composer').innerText()).not.toContain('/goal')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('把多个学院的老师放一起，来个你认为最好的导师的排名。只前30个最好的导师就够了。')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible()
  const table=page.getByTestId('artifact')
  await expect(table.locator('.rank-record')).toHaveCount(8)
  await expect(table).toContainText('30 条记录')
  const first=table.locator('.rank-record').first(),name=await first.locator('.rank-identity strong').innerText()
  const originalCollege=await first.locator('.rank-identity small').first().innerText()
  await first.getByRole('checkbox').check()
  const college=page.getByLabel('筛选推荐学院')
  const other=await college.locator('option').evaluateAll((options,current)=>options.find(option=>option.value&&option.value!==current)?.value,originalCollege)
  await college.selectOption(other)
  await expect(page.getByRole('region',{name:'待对比导师'})).toContainText(name)
  await expect(table.locator('.rank-select input:checked')).toHaveCount(0)
  const second=table.locator('.rank-record').first(),secondName=await second.locator('.rank-identity strong').innerText()
  await second.getByRole('checkbox').check()
  await page.getByRole('button',{name:'对比这 2 位',exact:true}).click()
  const comparison=page.getByRole('dialog',{name:'导师对比',exact:true})
  await expect(comparison).toContainText(name)
  await expect(comparison).toContainText(secondName)
  await page.keyboard.press('Escape')
  await college.selectOption('')
  await table.getByRole('button',{name:'表格',exact:true}).click()
  await expect(table.locator('thead th').first()).toContainText('推荐序')
  expect(await page.locator('.assistant-message').innerText()).not.toMatch(/工具调用上限|使用.*goal|完成 \d+ 步/)
  await page.getByRole('button',{name:'重新生成',exact:true}).click()
  await expect(page.getByRole('button',{name:'重新生成',exact:true})).toBeVisible()
  await expect(page.locator('.user-message')).toHaveCount(1)
  await expect(page.getByTestId('assistant-message')).toHaveCount(1)
})
test('重新生成遇到服务故障，旧答案及图表仍可读，重试完成后更新',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('重新生成保留验收：介绍导师培养情况')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'重新生成',exact:true})).toBeVisible()
  const original=await page.locator('.assistant-message .markdown').innerText()
  await page.getByRole('button',{name:'重新生成',exact:true}).click()
  await expect(page.getByRole('button',{name:'重试',exact:true})).toBeVisible()
  await expect(page.getByTestId('assistant-message')).toHaveCount(2)
  expect(await page.locator('.assistant-message .markdown').first().innerText()).toBe(original)
  await expect(page.getByTestId('artifact').first()).toBeVisible()
  await page.getByRole('button',{name:'重试',exact:true}).click()
  await expect(page.getByRole('button',{name:'重新生成',exact:true})).toBeVisible()
  await expect(page.getByTestId('assistant-message')).toHaveCount(1)
  await expect(page.locator('.message-error')).toHaveCount(0)
  await expect(page.locator('.user-message')).toHaveCount(1)
})

test('分类推荐合计30名，结果先出现，可切换、展开、查找、导出，移动端无来源墙',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('给我推荐一些最好的导师，全专业一起排名，排出你认为的最好的30个。而且最好分为两类，一类就业，一类读博。')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible()
  const result=page.getByRole('region',{name:'导师推荐结果'})
  await expect(result).toContainText('30 位导师 · 2 组结果')
  const employment=page.getByRole('tab',{name:/就业与项目/}),research=page.getByRole('tab',{name:/读博与科研/})
  await expect(employment).toHaveAttribute('aria-selected','true')
  await research.focus();await research.press('Home');await expect(employment).toBeFocused()
  await employment.press('ArrowRight');await expect(research).toHaveAttribute('aria-selected','true')
  const panel=page.getByRole('tabpanel'),records=panel.locator('.rank-record')
  await expect(records).toHaveCount(8)
  const details=panel.locator('.rank-record details').first()
  await details.locator('summary').click();await expect(details.locator('.rank-facts')).toBeVisible()
  const firstName=await records.first().locator('.rank-identity strong').innerText()
  await panel.getByRole('textbox',{name:'在表中查找'}).fill(firstName);await expect(records).toHaveCount(1)
  await panel.getByRole('textbox',{name:'在表中查找'}).fill('')
  const download=page.waitForEvent('download');await panel.getByRole('button',{name:/下载 .* CSV/}).click();expect((await download).suggestedFilename()).toMatch(/CSV|csv/)
  const sources=panel.locator('.source-links').first()
  await expect(sources).not.toHaveAttribute('open','')
  await sources.locator('summary').click();await expect(sources.locator('button').first()).toBeVisible()
  await sources.locator('button').first().click();await expect(page.getByRole('dialog',{name:'资料与来源'})).toBeVisible();await page.getByRole('button',{name:'关闭面板'}).click()
  await page.setViewportSize({width:390,height:844})
  await expect(panel.locator('.ranking-list')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
  await expect(research).toHaveAttribute('aria-selected','true')
  for(const tab of [employment,research]){const box=await tab.boundingBox();expect(box.x+box.width).toBeLessThanOrEqual(390)}
  expect(await page.getByTestId('assistant-message').innerText()).not.toMatch(/无法推荐|两类都不足|DSML/)
  const accessibility=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa']).analyze()
  expect(accessibility.violations.map(violation=>({id:violation.id,targets:violation.nodes.map(node=>node.target)}))).toEqual([])
})

test('失败显示未完成，可直接重试原问题，消息不重复且无需切换模式',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('一次失败重试验收：分析导师培养条件')
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'重试',exact:true})).toBeVisible({timeout:15000})
  await expect(page.locator('.work-trace summary')).toContainText('未完成')
  await page.getByRole('button',{name:'重试',exact:true}).click()
  await expect(page.getByRole('button',{name:'重新生成',exact:true})).toBeVisible()
  await expect(page.locator('.user-message')).toHaveCount(1)
  await expect(page.getByTestId('assistant-message')).toHaveCount(1)
  await expect(page.locator('.message-error')).toHaveCount(0)
  await expect(page.locator('.work-trace summary')).toContainText('已完成')
})
