import {test,expect} from '@playwright/test'

test('每个真实阶段即时展示，刷新仍可接续；完成后能展开阶段与耗时',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill('逐步进度验收：比较导师并可视化')
  const started=Date.now()
  await page.getByRole('button',{name:'发送问题'}).click()
  const trace=page.locator('.assistant-message').last().locator('.work-trace')
  await expect(trace).toBeVisible({timeout:1500})
  expect(Date.now()-started).toBeLessThan(1500)
  await expect(trace).toHaveAttribute('open','')
  await expect(trace.locator('.work-step.running')).toContainText(/理解|读取|准备|分析/)
  await expect(trace).toContainText('读取资料范围')
  await expect(trace).toContainText('查阅导师资料',{timeout:7000})
  await page.reload()
  await expect(trace).toBeVisible()
  await expect(trace.locator('.work-step.running')).toHaveCount(1)
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible({timeout:12000})
  await expect(trace).not.toHaveAttribute('open','')
  await trace.locator('summary').click()
  await expect(trace).toContainText('正在输出回答')
  await expect(trace).toContainText('绘制柱状图')
  await expect(trace.locator('.work-step.running')).toHaveCount(0)
  expect(await trace.innerText()).not.toMatch(/tool_calls|source_locator|mentor_id|PRIVATE_REASONING_TEST|reasoning_content/)
})
