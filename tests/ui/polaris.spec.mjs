test('推荐名单显示真实风险与优点标签、契合度和筛选漏斗，档案展示评价依据并可继续追问',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await page.request.put('/api/profile',{data:{goal:'career',musts:['internship','no_clock']}})
  await page.reload()
  await page.getByRole('textbox',{name:'向北极星提问'}).fill(ranking)
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible({timeout:15000})
  const funnel=page.locator('.funnel')
  await expect(funnel).toContainText('414');await expect(funnel).toContainText('最终名单')
  await expect(page.locator('.rank-record .flag-chip.tone-bad').first()).toBeVisible()
  await expect(page.locator('.rank-record .match-ring').first()).toBeVisible()
  await page.getByRole('button',{name:'查看导师档案 何召锋'}).click()
  const dossier=page.getByRole('dialog',{name:'导师档案'})
  await expect(dossier.getByRole('heading',{name:/何召锋/})).toBeVisible()
  await expect(dossier).toContainText('需要看清的风险')
  await expect(dossier).toContainText('打卡坐班')
  await expect(dossier.locator('svg.radar')).toBeVisible()
  await dossier.getByText('科研强度').click()
  await expect(dossier.locator('.radar-hint')).toContainText('/ 5')
  await audit(page)
  await dossier.getByRole('button',{name:/有什么坑/}).click()
  await expect(dossier).toHaveCount(0)
  await expect(page.locator('.user-message').last()).toContainText('何召锋（人工智能学院）有哪些坑')
  await expect(page.getByRole('button',{name:'复制回答'})).toHaveCount(2,{timeout:15000})
  expect(errors).toEqual([])
})

test('对决面板叠加雷达并标出胜出项，择导卡可下载为图片',async({page})=>{
  await page.goto('/')
  await page.getByRole('textbox',{name:'向北极星提问'}).fill(ranking)
  await page.getByRole('button',{name:'发送问题'}).click()
  await expect(page.getByRole('button',{name:'复制回答'})).toBeVisible({timeout:15000})
  const boxes=page.locator('.rank-select input')
  await boxes.nth(3).check();await boxes.nth(4).check()
  await page.getByRole('button',{name:/对比这/}).click()
  const duel=page.getByRole('region',{name:'导师对决'})
  await expect(duel.locator('svg.radar')).toBeVisible()
  await expect(duel.locator('.duel-person')).toHaveCount(2)
  await expect(duel).toContainText('胜出')
  await audit(page)
  await page.getByRole('button',{name:'关闭面板'}).click()
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:/择导卡/}).click()
  const file=await download
  expect(file.suggestedFilename()).toMatch(/北极星择导卡.*\.png$/)
})

