test('同名不同院在投影结果中使用 by:mentor_id 或姓名（学院）关联 row_notes 不触发 Catch-22',()=>{
  const runtime=createToolRuntime(data)
  const lius=data.mentors.filter(m=>m.name==='刘勇')
  assert.ok(lius.length>=2)
  const projected=runtime.execute('query',{from:'mentors',filters:[{field:'name',op:'eq',value:'刘勇'}],select:['name','college','rating','red_flags','review_text'],limit:20})
  const view=runtime.execute('visualize',{from:projected.ref,type:'table',title:'同名导师对比',select:['name','college','rating','red_flags'],row_notes:{by:'mentor_id',entries:lius.map(m=>({value:m.mentor_id,text:`${m.college}记录`}))}})
  assert.equal(view.artifact.rows.length,lius.length)
  assert.ok(!view.artifact.columns.some(c=>c.key==='mentor_id'))
  assert.deepEqual(view.artifact.row_notes,lius.map(m=>`${m.college}记录`))
  const byCollegeName=runtime.execute('visualize',{from:projected.ref,type:'table',title:'同名导师对比2',select:['name','college','rating'],row_notes:{by:'name',entries:lius.map(m=>({value:`${m.name}（${m.college}）`,text:`学院说明:${m.college}`}))}})
  assert.deepEqual(byCollegeName.artifact.row_notes,lius.map(m=>`学院说明:${m.college}`))
})
